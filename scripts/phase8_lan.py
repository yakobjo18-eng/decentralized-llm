def _free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


class _Proc:
    def __init__(self, name, args, cwd, log_dir: Path):
        self.name, self.args, self.cwd, self.log_dir = name, args, cwd, log_dir
        self.lines: "queue.Queue[str]" = queue.Queue()
        self.start()

    def start(self):
        self.log = (self.log_dir / f"{self.name}.log").open("a", encoding="utf-8")
        self.proc = subprocess.Popen(self.args, cwd=self.cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
                                     creationflags=getattr(subprocess, "CREATE_NEW_PROCESS_GROUP", 0))
        threading.Thread(target=self._pump, args=(self.proc, self.log), daemon=True).start()

    def _pump(self, proc, log):
        for line in proc.stdout:
            log.write(line)
            log.flush()
            self.lines.put(line)

    def wait_for(self, marker, timeout=180):
        end = time.time() + timeout
        while time.time() < end:
            try:
                if marker in self.lines.get(timeout=0.3):
                    return
            except queue.Empty:
                if self.proc.poll() is not None:
                    raise RuntimeError(f"{self.name} exited ({self.proc.returncode}); see {self.name}.log")
        raise TimeoutError(f"{self.name}: {marker!r} not seen")

    def stop(self, graceful=True):
        if self.proc.poll() is None:
            if graceful and hasattr(signal, "CTRL_BREAK_EVENT"):
                self.proc.send_signal(signal.CTRL_BREAK_EVENT)
                try:
                    self.proc.wait(timeout=20)
                except subprocess.TimeoutExpired:
                    self.proc.kill()
            else:
                self.proc.kill()
            self.proc.wait(timeout=10)
        self.log.close()


class LocalOperator:
    """Performs the disruptive actions on local processes (rehearsal/tests)."""

    def __init__(self, procs: Dict[str, _Proc]):
        self.procs = procs

    def stop_worker(self, wid):
        self.procs[wid].stop(graceful=True)

    def start_worker(self, wid):
        p = self.procs[wid]
        p.lines = queue.Queue()
        p.start()
        p.wait_for("StageExecution (protocol v1, UNAUTHENTICATED) listening on")

    def restart_orchestrator(self):
        p = self.procs["orchestrator"]
        p.stop(graceful=False)
        p.lines = queue.Queue()
        p.start()
        p.wait_for("REST API listening", 30)


def rehearse(out: Path, repeat: int = 2, allow_single_host: bool = True, with_operator: bool = True) -> int:
    """Everything `run` does, against a local orchestrator + 2 workers on 127.0.0.1."""
    out.mkdir(parents=True, exist_ok=True)
    work = out / "work"
    work.mkdir(exist_ok=True)
    rest, grpc_port = _free_port(), _free_port()
    (work / "orchestrator.yaml").write_text(orchestrator_config_text("127.0.0.1", grpc_port, "127.0.0.1", rest, 3, None, None),
                                            encoding="utf-8")
    procs: Dict[str, _Proc] = {}
    endpoints = {}
    try:
        procs["orchestrator"] = _Proc("orchestrator", [str(REPO / "orchestrator" / "orchestrator.exe"), "--config",
                                                       str(work / "orchestrator.yaml")], REPO / "orchestrator", out)
        procs["orchestrator"].wait_for("REST API listening", 30)
        for wid in ("rehearsal-a", "rehearsal-b"):
            ep = _free_port()
            (work / f"{wid}.yaml").write_text(
                worker_config_text(wid, f"127.0.0.1:{grpc_port}", "127.0.0.1", ep, "127.0.0.1", _free_port(), 0.5,
                                   extra="backend_compute_test: false\n"), encoding="utf-8")
            endpoints[wid] = f"127.0.0.1:{ep}"
            procs[wid] = _Proc(wid, [sys.executable, "-m", "worker.main", "--config", str(work / f"{wid}.yaml")],
                               REPO / "worker", out)
        for wid in endpoints:
            procs[wid].wait_for("StageExecution (protocol v1, UNAUTHENTICATED) listening on")

        def synthetic(records):
            from dataclasses import replace

            from partitioner import create_plan
            from partitioner.cost import CostModel
            from partitioner.execution.tiny_gpt2 import spec
            from partitioner.memory import Workload

            fake = [replace(records[w], ram_available_bytes=4 * 2**30, ram_usable_bytes=3 * 2**30) for w in endpoints]
            return create_plan(spec(), fake, workload=Workload(batch_size=2), cost_model=CostModel(throughput_preference="estimated"),
                               allow_unused_workers=False)

        run = Run(f"http://127.0.0.1:{rest}", endpoints, out, repeat=repeat, allow_single_host=allow_single_host,
                  operator=LocalOperator(procs) if with_operator else None, rehearsal_plan=synthetic, redact_local_ips=True)
        meta = {}
        try:
            meta = run.run()
            meta["rehearsal"] = "one machine, 127.0.0.1, processes started by `phase8_lan.py rehearse`"
        finally:
            rc = write_report(run, meta)
        return rc
    finally:
        for name in [n for n in procs if n != "orchestrator"] + ["orchestrator"]:
            if name in procs:
                try:
                    procs[name].stop(graceful=name != "orchestrator")
                except Exception:
                    pass


def cmd_rehearse(a) -> int:
    if not (REPO / "orchestrator" / "orchestrator.exe").exists():
        raise SystemExit("orchestrator/orchestrator.exe not built: cd orchestrator; go build -o orchestrator.exe ./cmd/orchestrator")
    return rehearse(Path(a.out).resolve(), a.repeat, allow_single_host=not a.strict, with_operator=not a.no_disruption)


