def _write(path: Path, text: str, force: bool) -> None:
    if path.exists() and not force:
        raise SystemExit(f"{path} exists; refusing to overwrite (pass --force after checking its contents)")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def _check_ip(value: str, what: str, allow_loopback: bool) -> str:
    kind = classify(value)
    if kind == "private" or (kind == "loopback" and allow_loopback):
        return kind
    reason = {"public": "a PUBLIC address", "all-interfaces": "every interface", "hostname": "a hostname, not an IP",
              "loopback": "loopback (pass --allow-loopback only for a one-machine rehearsal)"}.get(kind, kind)
    raise SystemExit(f"{what} {value!r} is {reason}; use this machine's PRIVATE LAN IPv4 address (ipconfig)")


def _port(value: int, what: str) -> int:
    if not 1 <= value <= 65535:
        raise SystemExit(f"{what} {value} is not a valid TCP port")
    return value


def orchestrator_config_text(lan_ip: str, grpc_port: int, rest_host: str, rest_port: int, heartbeat_timeout: float,
                             ram_margin_percent: Optional[float], ram_margin_min_gib: Optional[float]) -> str:
    stamp = dt.datetime.now().isoformat(timespec="seconds")
    lines = [
        f"# Generated by scripts/phase8_lan.py orchestrator-config on {stamp}; every value came from the command line.",
        "# UNAUTHENTICATED service: keep it on a trusted private LAN (docs/DEPLOYMENT_LAN.md).",
        f'grpc_address: "{lan_ip}:{grpc_port}"      # workers on other machines register here',
        f'rest_address: "{rest_host}:{rest_port}"   # the coordinator and preflight run on this machine',
        f"heartbeat_timeout_seconds: {heartbeat_timeout:g}",
        "allow_simulated_workers: false",
    ]
    if ram_margin_percent is not None or ram_margin_min_gib is not None:
        lines += ["# DEVIATION from the defaults (10% / 1 GiB): record it in the test report.", "capability:"]
        if ram_margin_percent is not None:
            lines.append(f"  ram_safety_margin_percent: {ram_margin_percent:g}")
        if ram_margin_min_gib is not None:
            lines.append(f"  ram_safety_margin_min_gib: {ram_margin_min_gib:g}")
    return "\n".join(lines) + "\n"


def worker_config_text(worker_id: str, orchestrator: str, execution_host: str, execution_port: int,
                       health_host: str, health_port: int, heartbeat_interval: float, extra: str = "") -> str:
    stamp = dt.datetime.now().isoformat(timespec="seconds")
    return "\n".join([
        f"# Generated by scripts/phase8_lan.py worker-config on {stamp}; every value came from the command line.",
        f'worker_id: "{worker_id}"',
        f'orchestrator_address: "{orchestrator}"',
        f'listen_host: "{health_host}"            # Health: nothing dials it remotely',
        f"listen_port: {health_port}",
        f"heartbeat_interval_seconds: {heartbeat_interval:g}",
        "execution_enabled: true",
        f'execution_listen_host: "{execution_host}"  # UNAUTHENTICATED StageExecution: private LAN IP or loopback only',
        f"execution_listen_port: {execution_port}",
        'simulated_profile: ""',
    ]) + "\n" + extra


def cmd_orchestrator_config(a) -> int:
    _check_ip(a.lan_ip, "--lan-ip", a.allow_loopback)
    if classify(a.rest_host) not in ("loopback", "private"):
        raise SystemExit(f"--rest-host {a.rest_host!r} must be loopback or a private IP")
    if a.grpc_port == a.rest_port and a.lan_ip == a.rest_host:
        raise SystemExit("gRPC and REST cannot share host:port")
    text = orchestrator_config_text(a.lan_ip, _port(a.grpc_port, "--grpc-port"), a.rest_host, _port(a.rest_port, "--rest-port"),
                                    a.heartbeat_timeout, a.ram_margin_percent, a.ram_margin_min_gib)
    _write(Path(a.out), text, a.force)
    print(f"wrote {a.out}\nnext: cd model-partitioner; python -m partitioner preflight --orchestrator-config {Path(a.out).resolve()}"
          + (f" --peer-ip <WORKER-MACHINE-IP>" if classify(a.lan_ip) == "private" else ""))
    return 0


def cmd_worker_config(a) -> int:
    if not WORKER_ID_RE.match(a.worker_id):
        raise SystemExit("--worker-id: 1-64 characters, letters/digits/._- , starting with a letter or digit")
    host, sep, port = a.orchestrator.rpartition(":")
    if not sep or not port.isdigit():
        raise SystemExit("--orchestrator must be HOST:PORT, e.g. <C1_IP>:9090")
    _check_ip(host, "--orchestrator host", a.allow_loopback)
    _port(int(port), "--orchestrator port")
    _check_ip(a.execution_host, "--execution-host", a.allow_loopback)
    if classify(a.health_host) not in ("loopback", "private"):
        raise SystemExit("--health-host must be loopback or a private IP")
    if a.health_port == a.execution_port:
        raise SystemExit("--health-port and --execution-port must differ")
    text = worker_config_text(a.worker_id, a.orchestrator, a.execution_host, _port(a.execution_port, "--execution-port"),
                              a.health_host, _port(a.health_port, "--health-port"), a.heartbeat_interval)
    _write(Path(a.out), text, a.force)
    print(f"wrote {a.out}\nnext: cd model-partitioner; python -m partitioner preflight --worker-config {Path(a.out).resolve()} "
          "--peer-ip <COORDINATOR-IP>   (add --probe-orchestrator once the orchestrator is running)")
    return 0


