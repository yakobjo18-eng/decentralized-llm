class InteractiveOperator:
    """Asks the human at the keyboard to perform each disruptive action."""

    def stop_worker(self, wid: str) -> None:
        input(f"\n>>> Stop worker {wid!r} now (Ctrl+C in its terminal on its machine), then press Enter... ")

    def start_worker(self, wid: str) -> None:
        input(f"\n>>> Start worker {wid!r} again (same command), wait for 'registered with orchestrator', then press Enter... ")

    def restart_orchestrator(self) -> None:
        input("\n>>> Restart the orchestrator (Ctrl+C in its terminal, then start it again), then press Enter... ")


def _get(url: str, timeout: float = 3.0):
    with urllib.request.urlopen(url, timeout=timeout) as r:
        return json.loads(r.read().decode("utf-8"))


def _wait(pred, timeout: float, what: str) -> float:
    t0 = time.time()
    while time.time() - t0 < timeout:
        try:
            if pred():
                return time.time() - t0
        except Exception:
            pass
        time.sleep(0.5)
    raise TimeoutError(f"timed out after {timeout:.0f}s waiting for {what}")


def _git() -> dict:
    def out(*args):
        try:
            return subprocess.run(["git", *args], cwd=REPO, capture_output=True, text=True, timeout=10).stdout.strip()
        except Exception:
            return None

    status = out("status", "--porcelain")
    return {"commit": out("rev-parse", "HEAD"), "branch": out("branch", "--show-current"),
            "uncommitted_changes": None if status is None else bool(status)}


class Run:
    def __init__(self, orchestrator_url: str, endpoints: Dict[str, str], out: Path, batch: int = 2,
                 tokens: str = DEFAULT_TOKENS, repeat: int = 3, plan_path: Optional[str] = None,
                 allow_single_host: bool = False, operator=None, probe_timeout: float = 240,
                 stage_timeout: float = 30, extra_safety: float = 0.10, rehearsal_plan=None, redact_local_ips: bool = False):
        self.url = orchestrator_url.rstrip("/")
        self.endpoints = dict(endpoints)
        self.out = out
        self.batch, self.tokens, self.repeat = batch, tokens, repeat
        self.plan_path, self.allow_single_host, self.operator = plan_path, allow_single_host, operator
        self.probe_timeout, self.stage_timeout, self.extra_safety = probe_timeout, stage_timeout, extra_safety
        self.rehearsal_plan = rehearsal_plan  # callable(records) -> plan; used by `rehearse` only
        # Rehearsal reports may be committed: keep this machine's non-loopback addresses out of them.
        self.redact_local_ips = redact_local_ips
        self.steps: List[dict] = []
        self.state: dict = {}
        out.mkdir(parents=True, exist_ok=True)

    # ---- bookkeeping ----------------------------------------------------

    def step(self, sid, title, fn, required=True):
        print(f"\n--- {sid}: {title}", flush=True)
        t = time.perf_counter()
        try:
            status, detail, evidence = fn()
        except Exception as exc:
            status, detail, evidence = "FAIL", f"{type(exc).__name__}: {exc}", {"traceback": traceback.format_exc()}
        self.steps.append({"id": sid, "title": title, "status": status, "detail": detail,
                           "seconds": round(time.perf_counter() - t, 3), "required": required, "evidence": evidence})
        print(f"    {status}: {detail}", flush=True)
        return status

    def skip_rest(self, ids_titles, why):
        for sid, title in ids_titles:
            self.steps.append({"id": sid, "title": title, "status": "SKIP", "detail": f"not run: {why}", "seconds": 0,
                               "required": True, "evidence": {}})

    def workers_view(self):
        return {w["id"]: w for w in _get(f"{self.url}/api/workers")}

    def save_preflight(self, rep, name: str) -> None:
        if self.redact_local_ips:
            for c in rep.checks:
                if c.section == "this machine" and c.name.startswith("IPv4 ") and not c.detail.startswith("loopback"):
                    c.name = "IPv4 <redacted>"
        (self.out / f"{name}.json").write_text(json.dumps(rep.to_dict(), indent=1), encoding="utf-8")
        (self.out / f"{name}.txt").write_text(rep.render(), encoding="utf-8")

    def execute(self, label: str, **opts):
        from partitioner.execution.remote import RemoteOptions, execute_plan_remote
        from partitioner.cli import _parse_tokens

        r = execute_plan_remote(self.state["plan"], _parse_tokens(self.tokens), self.endpoints,
                                options=RemoteOptions(stage_timeout_seconds=self.stage_timeout,
                                                      connect_timeout_seconds=opts.pop("connect_timeout", 3.0), **opts))
        name = re.sub(r"[^a-z0-9]+", "-", label.lower()).strip("-")
        (self.out / f"result-{name}.json").write_text(json.dumps(r, indent=1, default=str), encoding="utf-8")
        return r

    # ---- steps ---------------------------------------------------------

    def run(self) -> dict:
        from partitioner import preflight

        stage_workers = list(self.endpoints)
        meta = {"started_at": dt.datetime.now().isoformat(timespec="seconds"), "coordinator_hostname": socket.gethostname(),
                "platform": platform.platform(), "python": sys.version.split()[0], "orchestrator_url": self.url,
                "endpoints": self.endpoints, "batch": self.batch, "tokens": self.tokens, "repeat": self.repeat,
                "allow_single_host": self.allow_single_host, "git": _git()}

        def environment():
            ips = [(i, a if (k == "loopback" or not self.redact_local_ips) else "<redacted>", k)
                   for i, a, k in preflight.local_ipv4()]
            meta["coordinator_ipv4"] = ips
            g = meta["git"]
            ok = bool(g.get("commit"))
            return ("PASS" if ok else "WARN",
                    f"coordinator {socket.gethostname()}, commit {g.get('commit')} on {g.get('branch')}"
                    + (" (UNCOMMITTED changes present: record them)" if g.get("uncommitted_changes") else ""),
                    {"ipv4": ips, "git": g})

        self.step("P1", "coordinator environment (host, IPs, commit)", environment, required=False)

        def preflight_live():
            rep = preflight.run(orchestrator=self.url, expect=stage_workers, endpoints=self.endpoints, skip_runtime=False)
            self.save_preflight(rep, "preflight-live")
            fails = [f"{c.section}: {c.name}: {c.detail}" for c in rep.checks if c.status == "FAIL"]
            return ("FAIL" if fails else "PASS", f"{rep.counts()}" + (f"; FAILS: {fails}" if fails else ""),
                    {"counts": rep.counts()})

        def ready():
            # A worker logs "StageExecution listening" BEFORE it registers, and registers BEFORE its backend probe
            # finishes (planning refuses it until then), so wait for both. On timeout P3 still runs, to explain why.
            def state():
                try:
                    v = self.workers_view()
                except OSError as exc:
                    return {w: f"orchestrator unreachable ({exc})" for w in stage_workers}
                return {w: ("not registered" if w not in v else "offline" if not v[w].get("online")
                            else "backend probe running" if v[w].get("backend_probe_pending") else "ready") for w in stage_workers}

            try:
                waited = _wait(lambda: set(state().values()) == {"ready"}, self.probe_timeout,
                               "registered, online workers with finished backend probes")
            except TimeoutError:
                return "FAIL", f"not ready after {self.probe_timeout:.0f}s: {state()} (see the P3 preflight for why)", {}
            return "PASS", f"all {len(stage_workers)} workers registered, online, backend probes finished (waited {waited:.1f}s)", {}

        ready_status = self.step("P2", "wait for registrations and backend probes", ready)
        if self.step("P3", "preflight: orchestrator, registrations, endpoints, protocol", preflight_live) == "FAIL" \
                or ready_status == "FAIL":
            self.skip_rest([("P4", "plan"), ("P5", "preflight with plan"), ("P6", "execution"),
                            ("P7", "multi-machine criterion"), ("P8", "disconnect/restart")], "workers not ready / preflight failed")
            return meta

        def plan_step():
            from partitioner import create_plan
            from partitioner.cost import CostModel
            from partitioner.execution.tiny_gpt2 import spec
            from partitioner.memory import MemoryPolicy, Workload
            from partitioner.workers import from_orchestrator

            records = {w.worker_id: w for w in from_orchestrator(self.url)}
            missing = [w for w in stage_workers if w not in records]
            if missing:
                return "FAIL", f"workers missing from the orchestrator's resources view: {missing}", {}
            if self.plan_path:
                plan = json.loads(Path(self.plan_path).read_text(encoding="utf-8"))
                source = f"operator-supplied plan {self.plan_path} (NOT generated from live registrations)"
            else:
                plan = create_plan(spec(), [records[w] for w in stage_workers], workload=Workload(batch_size=self.batch),
                                   memory_policy=MemoryPolicy(extra_safety_fraction=self.extra_safety),
                                   cost_model=CostModel(throughput_preference="estimated"), allow_unused_workers=False)
                source = "generated from LIVE orchestrator registrations (REAL profiles only)"
                if not plan["feasible"] and self.rehearsal_plan is not None:
                    self.state["live_infeasibility"] = plan["infeasibility"]["reasons"]
                    plan = self.rehearsal_plan(records)
                    source = ("REHEARSAL: live registrations were INFEASIBLE on this machine; plan built from the same REAL "
                              "records with SYNTHETIC capacity -- rehearsal only")
            self.state["plan_source"] = source
            path = self.out / "plan.json"
            path.write_text(json.dumps(plan, indent=1), encoding="utf-8")
            if not plan.get("feasible"):
                reasons = (plan.get("infeasibility") or {}).get("reasons") or []
                return "FAIL", ("plan INFEASIBLE from live registrations: " + " | ".join(reasons)[:600]
                                + " -- free RAM or lower the orchestrator's capability margins (record the deviation)"), \
                    {"reasons": reasons, "source": source}
            self.state["plan"] = plan
            stages = [{"stage": s["stage_index"], "worker": s["worker_id"], "host": s.get("hostname"),
                       "units": s["unit_range"]} for s in plan["stages"]]
            ok = sorted(s["worker"] for s in stages) == sorted(stage_workers)
            return ("PASS" if ok else "FAIL", f"{source}; plan {plan['inputs_fingerprint'][:16]}...; stages {stages}",
                    {"source": source, "stages": stages, "live_infeasibility": self.state.get("live_infeasibility")})

        if self.step("P4", "plan the tiny model across the endpoint workers", plan_step) == "FAIL":
            self.skip_rest([("P5", "preflight with plan"), ("P6", "execution"), ("P7", "multi-machine criterion"),
                            ("P8", "disconnect/restart")], "no feasible plan")
            return meta

        def preflight_plan():
            rep = preflight.run(orchestrator=self.url, endpoints=self.endpoints, plan=str(self.out / "plan.json"),
                                require_multi_host=not self.allow_single_host, skip_runtime=True)
            self.save_preflight(rep, "preflight-plan")
            fails = [f"{c.section}: {c.name}: {c.detail}" for c in rep.checks if c.status == "FAIL"]
            return ("FAIL" if fails else "PASS", f"{rep.counts()}" + (f"; FAILS: {fails}" if fails else ""),
                    {"counts": rep.counts()})

        self.step("P5", "preflight: plan, assignment, limits" + ("" if self.allow_single_host else ", multi-host"),
                  preflight_plan)

        def execution():
            rows = []
            for i in range(1, self.repeat + 1):
                r = self.execute(f"run {i}")
                ref = r.get("reference_check") or {}
                rows.append({"run": i, "status": r["status"], "max_abs_diff": ref.get("max_abs_diff"), "atol": ref.get("atol"),
                             "next_token_ids": (r.get("output") or {}).get("next_token_ids"),
                             "output_shape": (r.get("output") or {}).get("shape"),
                             "elapsed_seconds": round(r["elapsed"]["total_seconds"], 4),
                             "test_classification": r.get("test_classification"),
                             "stages": [{"stage": s["stage_index"], "worker": s["worker_id"], "endpoint": s["endpoint"],
                                         "reported": s.get("worker_reported"),
                                         "round_trip_seconds": round(s.get("round_trip_seconds", 0), 4)} for s in r["stages"]],
                             "error": (r.get("error") or {}).get("message")})
                self.state.setdefault("results", []).append(r)
            ok = all(x["status"] == "succeeded" and x["max_abs_diff"] is not None and x["max_abs_diff"] <= x["atol"]
                     for x in rows)
            return ("PASS" if ok else "FAIL",
                    "; ".join(f"run {x['run']}: {x['status']}, diff {x['max_abs_diff']}, {x['elapsed_seconds']}s"
                              for x in rows) + " (single runs, not a benchmark)", {"runs": rows})

        self.step("P6", f"execute the plan remotely x{self.repeat}, compare with the local reference", execution)

        def criterion():
            results = [r for r in self.state.get("results", []) if r["status"] == "succeeded"]
            if not results:
                return "FAIL", "no successful execution to judge", {}
            status, detail, evidence = judge(results[-1], self.workers_view(), self.allow_single_host)
            self.state["classification"] = evidence["classification"]
            return status, detail, evidence

        self.step("P7", "multi-machine criterion (evidence-based classification)", criterion)

        if self.operator is None:
            self.skip_rest([("P8", "disconnect/restart")], "no --interactive operator")
        else:
            self.step("P8", "disconnect/restart: worker stop, restart, orchestrator restart", self.resilience)
        meta["finished_at"] = dt.datetime.now().isoformat(timespec="seconds")
        return meta

    def resilience(self):
        here = socket.gethostname()
        stages = self.state["plan"]["stages"]
        remote = [s["worker_id"] for s in stages if s.get("hostname") != here]
        victim = (remote or [stages[-1]["worker_id"]])[-1]
        notes, ok = [], True
        self.operator.stop_worker(victim)
        gone = _wait(lambda: not self.workers_view().get(victim, {}).get("online", False), 60, f"{victim} offline/deregistered")
        down = self.execute("while worker down", max_attempts=2, connect_timeout=2.0, retry_backoff_seconds=0.2)
        e = down.get("error") or {}
        safe = down["status"] == "failed" and e.get("executed") is False
        ok &= safe
        notes.append(f"stopped {victim}: offline after {gone:.1f}s; execution {down['status']} "
                     f"({e.get('code')}, executed={e.get('executed')})")
        self.operator.start_worker(victim)
        back = _wait(lambda: (lambda w: w.get("online") and not w.get("backend_probe_pending"))(
            self.workers_view().get(victim, {})), self.probe_timeout, f"{victim} back with finished probe")
        up = self.execute("after worker restart")
        ok &= up["status"] == "succeeded"
        notes.append(f"restarted: ready after {back:.1f}s; execution {up['status']}")
        self.operator.restart_orchestrator()
        rereg = _wait(lambda: all(self.workers_view().get(w, {}).get("online") for w in self.endpoints), 120,
                      "re-registration after orchestrator restart")
        after = self.execute("after orchestrator restart")
        ok &= after["status"] == "succeeded"
        notes.append(f"orchestrator restarted: all workers re-registered within {rereg:.1f}s; execution {after['status']}")
        return ("PASS" if ok else "FAIL", "; ".join(notes),
                {"victim": victim, "down_error": {k: e.get(k) for k in ("code", "executed", "stage_index", "message")}})


def judge(result: dict, workers_view: Dict[str, dict], allow_single_host: bool = False):
    """The multi-machine verdict for one successful remote result.

    REAL_MULTI_MACHINE needs BOTH >= 2 distinct worker-reported hostnames
    (self-asserted) AND >= 2 distinct non-loopback IPs that the
    orchestrator saw the workers' registrations come from (TCP peers).
    Either alone is not enough: hostnames are just strings, and one
    multi-homed machine can register from two IPs."""
    per_worker = {}
    for s in result["stages"]:
        rec = workers_view.get(s["worker_id"], {})
        per_worker[s["worker_id"]] = {"reported_hostname": s["worker_reported"]["hostname"],
                                      "reported_pid": s["worker_reported"]["pid"], "endpoint": s["endpoint"],
                                      "orchestrator_observed_peer_ip": rec.get("observed_peer_ip"),
                                      "orchestrator_hostname": rec.get("hostname"),
                                      "registered_address": rec.get("address")}
    hosts = {v["reported_hostname"] for v in per_worker.values()}
    peers = {v["orchestrator_observed_peer_ip"] for v in per_worker.values()
             if v["orchestrator_observed_peer_ip"] and classify(v["orchestrator_observed_peer_ip"]) != "loopback"}
    procs = {(v["reported_hostname"], v["reported_pid"]) for v in per_worker.values()}
    multi = len(hosts) >= 2 and len(peers) >= 2
    klass = "REAL_MULTI_MACHINE" if multi else ("REAL_MULTI_PROCESS" if len(procs) > 1 else "REAL_SINGLE_MACHINE")
    evidence = {"per_worker": per_worker, "distinct_reported_hostnames": sorted(hosts),
                "distinct_non_loopback_peer_ips": sorted(peers), "classification": klass,
                "basis": "worker self-reported hostnames (unauthenticated) AND the IPs the orchestrator saw their "
                         "registrations come from (TCP peer addresses)"}
    detail = (f"classification {klass}: {len(hosts)} reported hostname(s) {sorted(hosts)}, {len(peers)} non-loopback "
              f"registration peer IP(s) {sorted(peers)}")
    if multi:
        return "PASS", detail, evidence
    if allow_single_host:
        return "PASS", detail + " -- REHEARSAL (--allow-single-host): multi-machine criterion NOT met and NOT claimed", evidence
    return "FAIL", detail + " -- multi-machine criterion NOT met", evidence


def write_report(run: Run, meta: dict) -> int:
    fails = [s["id"] for s in run.steps if s["status"] == "FAIL" and s["required"]]
    klass = run.state.get("classification", "NOT DETERMINED (no successful execution)")
    report = {"phase8_lan_report_schema_version": 1, "meta": meta, "classification": klass,
              "plan_source": run.state.get("plan_source"), "steps": run.steps, "failed_steps": fails,
              "result": "PASS" if not fails else "FAIL"}
    (run.out / "report.json").write_text(json.dumps(report, indent=2, default=str), encoding="utf-8")
    g = meta.get("git", {})
    lines = [
        f"# Phase 8 LAN test -- {meta.get('started_at', '')}", "",
        f"- **Result:** {'PASS' if not fails else 'FAIL'}" + (f" (failed: {', '.join(fails)})" if fails else ""),
        f"- **Classification:** `{klass}`" + (" (rehearsal: --allow-single-host)" if run.allow_single_host else ""),
        f"- Coordinator: `{meta.get('coordinator_hostname')}`, {meta.get('platform')}, Python {meta.get('python')}",
        f"- Commit: `{g.get('commit')}` on `{g.get('branch')}`" + (" -- **uncommitted changes present**" if g.get("uncommitted_changes") else ""),
        f"- Orchestrator: {meta.get('orchestrator_url')}; endpoints: " + ", ".join(f"`{k}={v}`" for k, v in run.endpoints.items()),
        f"- Plan source: {run.state.get('plan_source') or '-'}",
        "- Timings are single-run wall clock, not benchmarks.", "",
        "| Step | Title | Result | Time | Detail |", "|---|---|---|---|---|",
    ]
    for s in run.steps:
        lines.append(f"| {s['id']} | {s['title']} | **{s['status']}** | {s['seconds']:.2f}s | "
                     f"{str(s['detail']).replace('|', '/').replace(chr(10), ' ')} |")
    crit = next((s for s in run.steps if s["id"] == "P7" and s.get("evidence")), None)
    if crit:
        lines += ["", "## Evidence per worker", "", "| Worker | Reported host | Reported pid | Endpoint | Orchestrator saw it register from |",
                  "|---|---|---|---|---|"]
        for wid, v in crit["evidence"]["per_worker"].items():
            lines.append(f"| {wid} | {v['reported_hostname']} | {v['reported_pid']} | {v['endpoint']} | {v['orchestrator_observed_peer_ip']} |")
    lines += ["", "Files: `preflight-live.txt`, `preflight-plan.txt`, `plan.json`, `result-*.json`, `report.json`."]
    (run.out / "report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nRESULT {report['result']} -- classification {klass} -- report: {run.out / 'report.md'}")
    return 0 if not fails else 1


def cmd_run(a) -> int:
    from partitioner.execution.remote import parse_endpoint

    endpoints = {}
    for item in a.endpoint:
        wid, addr = parse_endpoint(item)
        endpoints[wid] = addr
    if len(endpoints) < 2:
        raise SystemExit("give at least two --endpoint WORKER_ID=HOST:PORT (one per stage worker)")
    run = Run(a.orchestrator_url, endpoints, Path(a.out).resolve(), a.batch, a.tokens, a.repeat, a.plan,
              a.allow_single_host, InteractiveOperator() if a.interactive else None, a.probe_timeout, a.stage_timeout,
              a.extra_safety)
    meta = {}
    try:
        meta = run.run()
    finally:
        rc = write_report(run, meta)
    return rc


