"""Phase 8: two-machine LAN test tooling (docs/DEPLOYMENT_LAN.md).

All addresses and ports come from the command line; nothing about any
real network is built in.

  orchestrator-config  write a validated orchestrator.yaml (Computer 1)
      python scripts/phase8_lan.py orchestrator-config --lan-ip <C1_IP> --out orchestrator/orchestrator.yaml

  worker-config        write a validated worker YAML (any machine)
      python scripts/phase8_lan.py worker-config --worker-id computer-2-b --orchestrator <C1_IP>:9090 \\
          --execution-host <C2_IP> --execution-port 50201 --out worker/worker-b.yaml

  run                  THE two-machine test, run on the coordinator (Computer 1) once the orchestrator and every
                       worker are up. Preflight -> wait for backend probes -> plan from LIVE registrations ->
                       preflight with the plan -> execute N times -> evidence-based classification -> optional
                       guided disconnect/restart (--interactive). Writes report.md / report.json into --out.
      python scripts/phase8_lan.py run --orchestrator-url http://127.0.0.1:8080 \\
          --endpoint computer-1-a=127.0.0.1:50200 --endpoint computer-2-b=<C2_IP>:50201 --out docs/validation/phase8-lan-<date>

  rehearse             start a LOCAL orchestrator + 2 workers on 127.0.0.1 and exercise `run` end to end on this one
                       machine (classification REAL_MULTI_PROCESS; it can never produce REAL_MULTI_MACHINE).

Classification (run): REAL_MULTI_MACHINE only if the stage workers report >= 2 distinct hostnames AND the
orchestrator observed their registrations from >= 2 distinct non-loopback IPs. Otherwise the multi-machine
criterion step FAILS (unless --allow-single-host, which marks the run as a rehearsal and keeps the honest class).
"""

